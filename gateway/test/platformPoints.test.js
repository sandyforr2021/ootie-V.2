import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('platform points: atomic 2 per garment, idempotency, full failed outfit refund and cleanup isolation',async()=>{
 const db=new PGlite(),user=randomUUID(),profile=randomUUID(),ids=[randomUUID(),randomUUID(),randomUUID()];
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
   create schema auth;create table auth.users(id uuid primary key);
   create function auth.uid() returns uuid language sql as $$select null::uuid$$;
   grant usage on schema public,auth to anon,authenticated,service_role;
   create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table ootie_profiles(id uuid primary key,user_id uuid unique);
   create table ootie_point_transactions(id uuid primary key default gen_random_uuid(),profile_id uuid,amount integer,type text check(type in ('BIRTHDAY_BONUS','AI_USAGE','TRYON_USAGE','MANUAL_ADJUSTMENT','SUBSCRIPTION_GRANT','CREDIT_PURCHASE','PROMOTIONAL_REWARD')),source_key text,metadata jsonb,unique(profile_id,source_key));`);
  for(const name of ['20261022103816_youcam_commerce_jobs','20261023091242_youcam_safety_and_recovery','20261028055028_sequential_outfit_jobs','20261028100841_platform_generation_points'])await db.exec(await readFile(new URL(`../../supabase/migrations/${name}.sql`,import.meta.url),'utf8'));
  await db.query('insert into auth.users values($1)',[user]);await db.query('insert into ootie_profiles values($1,$2)',[profile,user]);
  await db.exec("update ootie_youcam_budget set unit_limit=100,reviewer_reserve_units=0,expires_at=now()+interval '1 day'");
  for(const id of ids)await db.query("insert into ootie_shop_products(id,user_id,title,image_path,category)values($1,$2,'shirt','image','upper_body')",[id,user]);
  const enqueue=(batch,list=ids)=>db.query('select * from enqueue_ootie_outfit($1,$2,$3,$4,false)',[batch,user,`person/${user}/photo.jpg`,list]);
  const balance=async()=>Number((await db.query('select coalesce(sum(amount),0) as n from ootie_point_transactions where profile_id=$1',[profile])).rows[0].n);
  await assert.rejects(enqueue(randomUUID()),/INSUFFICIENT_POINTS/);
  assert.equal((await db.query('select count(*) as n from ootie_youcam_jobs')).rows[0].n,0);
  await db.query("insert into ootie_point_transactions(profile_id,amount,type,source_key) values($1,10,'PROMOTIONAL_REWARD','test-grant')",[profile]);
  const batch=randomUUID(),jobs=(await enqueue(batch)).rows;
  assert.deepEqual(jobs.map(j=>j.platform_points),[2,2,2]);assert.equal(await balance(),4);
  await enqueue(batch);assert.equal(await balance(),4);
  await db.query("update ootie_youcam_jobs set status='succeeded',result_path='result' where id=$1",[jobs[0].id]);
  await db.query("update ootie_youcam_jobs set status='failed' where id=$1",[jobs[1].id]);assert.equal(await balance(),10);
  await db.query("update ootie_youcam_jobs set status='failed' where batch_id=$1 and status='queued'",[batch]);assert.equal(await balance(),10);
  await db.query("update ootie_youcam_jobs set status='cancelled' where id=$1",[jobs[1].id]);assert.equal(await balance(),10);
  const clean=(await db.query("select * from enqueue_ootie_youcam($1,$2,$3,'{}','garment_cleanup',false)",[randomUUID(),user,`shop/${user}/cleanup.jpg`])).rows[0];
  assert.equal(clean.units,1);assert.equal(clean.platform_points,2);assert.equal(await balance(),8);
  await db.query("update ootie_youcam_jobs set status='needs_review' where id=$1",[clean.id]);assert.equal(await balance(),8);
  await db.query("update ootie_youcam_jobs set status='failed' where id=$1",[clean.id]);assert.equal(await balance(),10);
  const success=(await enqueue(randomUUID(),[ids[0]])).rows[0];
  await db.query("update ootie_youcam_jobs set status='succeeded',result_path='result' where id=$1",[success.id]);
  await db.query("update ootie_youcam_jobs set result_path=null,result_deleted_at=now() where id=$1",[success.id]);
  assert.equal(await balance(),8,'deleting a successful image must not refund generation');
  assert.equal(Number((await db.query('select ootie_platform_point_balance($1) balance',[user])).rows[0].balance),8);
  const reviewJobs=(await enqueue(randomUUID(),ids.slice(0,2))).rows;
  assert.equal(await balance(),4);
  await db.query("update ootie_youcam_jobs set status='needs_review' where id=$1",[reviewJobs[0].id]);
  await db.query("update ootie_youcam_jobs set status='failed' where id=$1",[reviewJobs[1].id]);
  assert.equal(await balance(),4,'uncertain provider outcome is held for review');
  await db.query("update ootie_youcam_jobs set status='succeeded' where id=$1",[reviewJobs[0].id]);
  assert.equal(await balance(),8,'resolving review refunds a batch that has no final outfit');
  await assert.rejects(db.query("select * from enqueue_ootie_youcam($1,$2,'shop/another/cleanup.jpg','{}','garment_cleanup',false)",[randomUUID(),user]),/PERSON_IMAGE_NOT_OWNED/);
  await db.exec(await readFile(new URL('../../supabase/migrations/20261028104917_member_daily_generation_limit.sql',import.meta.url),'utf8'));
  await db.exec("update ootie_youcam_jobs set created_at=now()-interval '2 days'");
  await db.query("insert into ootie_point_transactions(profile_id,amount,type,source_key) values($1,100,'PROMOTIONAL_REWARD','daily-limit-test')",[profile]);
  const dailyBefore=await balance();
  const dailyBatch=randomUUID();const dailyJobs=(await enqueue(dailyBatch)).rows;
  await db.query("update ootie_youcam_jobs set status='succeeded',result_path='result' where batch_id=$1",[dailyBatch]);
  assert.equal(dailyJobs.length,3);
  const dailyClean=(await db.query("select * from enqueue_ootie_youcam($1,$2,$3,'{}','garment_cleanup',false)",[randomUUID(),user,`shop/${user}/daily.jpg`])).rows[0];
  assert.equal(await balance(),dailyBefore-8);
  const quota=()=>db.query('select get_ootie_youcam_user_quota($1) q',[user]);
  assert.equal((await quota()).rows[0].q.generationUsed,2,'three-item outfit consumes one submission');
  await enqueue(dailyBatch);assert.equal(await balance(),dailyBefore-8,'replay does not consume points or slots');
  await assert.rejects(enqueue(randomUUID(),[ids[0]]),/DAILY_GENERATION_LIMIT/);
  assert.equal(await balance(),dailyBefore-8,'blocked third request rolls back debit');
  await db.query("update ootie_youcam_jobs set status='failed' where id=$1",[dailyClean.id]);
  assert.equal((await quota()).rows[0].q.generationUsed,1,'confirmed failure returns its daily slot');
  await enqueue(randomUUID(),[ids[0]]);
  assert.equal((await quota()).rows[0].q.generationUsed,2);
  assert.equal((await db.query('select ootie_daily_generation_count($1) n',[randomUUID()])).rows[0].n,0,'other members have independent limits');
  await db.exec("update ootie_youcam_jobs set created_at=(date_trunc('day',now() at time zone 'Asia/Taipei') at time zone 'Asia/Taipei')-interval '1 second'");
  assert.equal((await quota()).rows[0].q.generationUsed,0,'resets at Taiwan midnight');
  await db.exec('set role authenticated');await assert.rejects(enqueue(randomUUID()),/permission denied/);
 }finally{await db.close();}
});
